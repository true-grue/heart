def parse_dsl(dsl):
    world = {}
    for line in dsl.strip().splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue

        match line.split():
            case ['ROOM', room_id]:
                world[room_id] = room = {
                    'name': '',
                    'desc': [],
                    'cmds': [],
                    'tests': [],
                }
            case ['NAME', *words]:
                room['name'] = ' '.join(words)
            case ['DESC', condition, *words]:
                room['desc'].append((condition, ' '.join(words)))
            case ['TEST', condition, ':', effect, *words]:
                room['tests'].append((condition, effect, words))
            case [verb, obj, condition, ':', effect, *words]:
                room['cmds'].append((verb, obj.replace('_', ' '), condition, effect, words))
    return world       

def check(conditions, state):
    for condition in conditions.split(','):
        if condition == '*':
            continue
        if condition.startswith('~'):
            if condition[1:] in state:
                return False
        elif condition not in state:
            return False
    return True

def menu(prompt, options):
    for index, option in enumerate(options, 1):
        print(f"  {index}. {option.capitalize()}")
    while True:
        try:
            choice = int(input(prompt)) - 1
            if 0 <= choice < len(options):
                return options[choice]
        except ValueError:
            pass

def apply(effect, args, state):
    if effect in ('end', 'win'):
        tag = 'ПОБЕДА' if effect == 'win' else 'ВЫ ПОГИБЛИ'
        print(f"[{tag}] {' '.join(args)}")
        return None, '', True

    if effect == 'goto':
        return args[0], ' '.join(args[1:]), False

    if effect == 'give':
        state.add(args[0])
        return None, ' '.join(args[1:]), False

    return None, ' '.join(args), False

def run_game(start, state, world):
    room_id = start
    message = ''

    while True:
        room = world[room_id]

        triggered = False
        for condition, effect, words in room['tests']:
            if check(condition, state):
                new_room, message, game_over = apply(effect, words, state)
                if game_over:
                    return
                room_id = new_room or room_id
                triggered = True
                break
        if triggered:
            continue

        if message:
            print(f"\n> {message}\n")
            message = ''

        print(f"# {room['name'].upper()}")
        visible_text = ' '.join(
            text
            for condition, text in room['desc']
            if check(condition, state)
        )
        print(visible_text)

        available = {}
        for verb, obj, condition, effect, words in room['cmds']:
            if check(condition, state):
                available.setdefault(verb, {})[obj] = (effect, words)

        print("Действия:")
        verbs = list(available) + ['инвентарь', 'рестарт']
        chosen_verb = menu("Ваш выбор: ", verbs)

        if chosen_verb == 'рестарт':
            return

        if chosen_verb == 'инвентарь':
            items = sorted(flag for flag in state if not flag.startswith('_'))
            message = 'Инвентарь: ' + (', '.join(items) if items else 'пуст')
            continue

        print(f"{chosen_verb.upper()} ->")
        objects = list(available[chosen_verb]) + ['отмена']
        chosen_object = menu("К чему: ", objects)
        if chosen_object == 'отмена':
            continue

        effect, words = available[chosen_verb][chosen_object]
        new_room, message, game_over = apply(effect, words, state)
        if game_over:
            return
        room_id = new_room or room_id

